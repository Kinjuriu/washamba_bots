import re, sys, os
S = os.environ.get("WA_DIR", os.path.dirname(os.path.abspath(__file__)))
BASE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(S, "w3_herdsafe2700.py")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(S, "wantam_h336.py")
H = int(os.environ.get("H_STEP", "336"))
rx = re.compile(r"^\s*(from|import)\s+(price_model|value_model|dump_predictor|sell_engine|controller)\b")
def strip(t):
    return "\n".join(l for l in t.splitlines() if not rx.match(l)) + "\n"
parts = []
base = open(BASE).read()
parts.append("# Washamba Bots: WANTAM hybrid. W3 herdsafe base to step %d, then WANTAM dawn planner\n# with the splice executor and sell engine. Generated by build_wantam.py.\n" % H)
parts.append(base if base.endswith("\n") else base + "\n")
parts.append("\n_WB_BASE = [_wb_v for _wb_v in list(globals().values()) if callable(_wb_v)][-1]\n")
for m in ["price_model.py", "value_model.py", "dump_predictor.py", "sell_engine.py", "controller.py"]:
    parts.append("\n# ---- %s ----\n" % m + strip(open(os.path.join(S, m)).read()))
WA_CTRL_CLASS = os.environ.get("WA_CTRL_CLASS", "WantamController")
w = open(os.path.join(S, "wantam.py")).read()
w = re.sub(r"from controller import \([^)]*\)\n", "", w)
w = w.replace("import controller as _wa_ctrl\n", "").replace("_wa_ctrl.", "")
assert "_wa_ctrl" not in w and "from controller" not in w
parts.append("\n# ---- wantam.py ----\n" + w + "\n")
parts.append('''
# ---- dispatcher ----
WB_HANDOVER_STEP = %d
WB_CTRL_CLASS = "%s"
_wb_dp = None
_WB_CONTROLLER = None
_WB_CONTROLLER_ERROR = None
try:
    _wb_pm = WB_PriceModel()
    _wb_dp = WB_DumpPredictor(_wb_pm)
    _wb_se = WB_SellEngine(_wb_pm, predictor=_wb_dp)
    _WB_CONTROLLER = {"WantamController": WantamController, "WantamExec": WantamExec,
                       "WantamScoreExec": WantamScoreExec}[WB_CTRL_CLASS](_wb_pm, _wb_se)
except Exception as _wb_construct_exc:
    _WB_CONTROLLER_ERROR = _wb_construct_exc


def _wb_call(fn, obs, config):
    args = [obs, config]
    if hasattr(fn, "__code__") and hasattr(fn.__code__, "co_argcount"):
        args = args[: fn.__code__.co_argcount]
    return fn(*args)


def _wb_safe_action(obs):
    farm = obs["farms"][obs["player"]]
    tiles = farm["tiles"]

    def _wb_act_for(pos):
        x, y = pos
        tile = tiles[y][x]
        if isinstance(tile, dict):
            if tile.get("kind") == "PLANT" and not tile.get("watered_today"):
                return ["WATER"]
            if "animal" in tile and not tile.get("fed_today"):
                return ["FEED"]
        return ["PASS"]

    return {"farmer": _wb_act_for(farm["farmer"]),
            "hands": [_wb_act_for(h) for h in farm["hands"]],
            "market": []}


def washamba_agent(obs, config=None):
    if _wb_dp is not None:
        try:
            _wb_dp.observe(obs)
        except Exception:
            pass
    if _WB_CONTROLLER is None or obs["step"] < WB_HANDOVER_STEP:
        return _wb_call(_WB_BASE, obs, config)
    try:
        return _WB_CONTROLLER.act(obs)
    except Exception:
        return _wb_safe_action(obs)


agent = washamba_agent
''' % (H, WA_CTRL_CLASS))
open(OUT, "w").write("".join(parts))
print("wrote", OUT, sum(len(p) for p in parts))
